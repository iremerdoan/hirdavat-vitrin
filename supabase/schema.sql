-- ---------- TABLOLAR ----------

create table if not exists public.ayarlar (
  id int primary key default 1 check (id = 1),     -- tek satırlık ayar tablosu
  dukkan_adi text not null default 'Hırdavat',
  slogan text default '',
  whatsapp text default '',                         -- örn: 0532 123 45 67
  adres text default '',
  calisma_saatleri text default ''
);
insert into public.ayarlar (id) values (1) on conflict do nothing;

-- Yönetim paneline girebilecek e-postalar (sadece dükkan sahibi)
create table if not exists public.yoneticiler (
  email text primary key
);

create table if not exists public.urunler (
  id bigint generated by default as identity primary key,
  kod text not null unique,                         -- Excel eşleştirmesi bu koda göre yapılır
  ad text not null,
  kategori text default 'Genel',
  birim text default 'Adet',
  fiyat numeric(12,2) not null default 0 check (fiyat >= 0),   -- KDV HARİÇ birim fiyat
  kdv int not null default 20 check (kdv between 0 and 100),
  stok int not null default 0,
  aktif boolean not null default true,              -- false ise vitrinde görünmez
  aciklama text default '',
  resimler text[] not null default '{}',
  olusturma timestamptz not null default now(),
  guncelleme timestamptz not null default now()
);

-- Vitrin hareketleri: ziyaret, ürün görüntüleme, "Al" tıklaması
create table if not exists public.olaylar (
  id bigint generated always as identity primary key,
  tur text not null check (tur in ('ziyaret', 'goruntuleme', 'al_tik')),
  urun_id bigint references public.urunler(id) on delete cascade,
  ziyaretci text not null check (char_length(ziyaretci) <= 64),   -- isimsiz tarayıcı kimliği
  zaman timestamptz not null default now()
);
create index if not exists olaylar_zaman_idx on public.olaylar (zaman);
create index if not exists olaylar_urun_idx on public.olaylar (urun_id, zaman);

-- Dükkan sahibinin girdiği satışlar
create table if not exists public.satislar (
  id bigint generated always as identity primary key,
  urun_id bigint references public.urunler(id) on delete set null,
  adet int not null check (adet > 0),
  birim_fiyat numeric(12,2) not null,               -- KDV hariç
  kdv int not null default 20,
  musteri text default '',
  zaman timestamptz not null default now()
);
create index if not exists satislar_zaman_idx on public.satislar (zaman);

-- Ürün güncellenince zaman damgası
create or replace function public.guncelleme_zamani() returns trigger
language plpgsql as $$ begin new.guncelleme = now(); return new; end $$;
drop trigger if exists urun_guncelleme on public.urunler;
create trigger urun_guncelleme before update on public.urunler
  for each row execute function public.guncelleme_zamani();

-- ---------- YETKİ ----------

create or replace function public.yonetici_mi() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.yoneticiler
    where lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;

alter table public.ayarlar     enable row level security;
alter table public.yoneticiler enable row level security;   -- kural yok = dışarıdan kimse okuyamaz
alter table public.urunler     enable row level security;
alter table public.olaylar     enable row level security;
alter table public.satislar    enable row level security;

drop policy if exists "ayar_oku" on public.ayarlar;
create policy "ayar_oku" on public.ayarlar for select using (true);
drop policy if exists "ayar_yaz" on public.ayarlar;
create policy "ayar_yaz" on public.ayarlar for all to authenticated
  using (public.yonetici_mi()) with check (public.yonetici_mi());

drop policy if exists "urun_oku" on public.urunler;
create policy "urun_oku" on public.urunler for select using (aktif or public.yonetici_mi());
drop policy if exists "urun_yaz" on public.urunler;
create policy "urun_yaz" on public.urunler for all to authenticated
  using (public.yonetici_mi()) with check (public.yonetici_mi());

