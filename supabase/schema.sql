-- Son 90 günde en çok satılan ürünler
create or replace function public.cok_satanlar(n int default 8)
returns table (id bigint, kod text, ad text, kategori text, birim text, fiyat numeric, kdv int,
               stok int, aktif boolean, aciklama text, resimler text[], satilan bigint)
language sql stable security definer set search_path = public as $$
  select u.id, u.kod, u.ad, u.kategori, u.birim, u.fiyat, u.kdv, u.stok, u.aktif, u.aciklama, u.resimler,
         sum(s.adet)::bigint as satilan
  from public.satislar s
  join public.urunler u on u.id = s.urun_id
  where u.aktif and s.zaman > now() - interval '90 days'
  group by u.id
  order by satilan desc
  limit least(greatest(n, 1), 24);
$$;

-- Alt bilgideki ziyaretçi sayıları ve son 30 günün en çok bakılan ürünleri
create or replace function public.vitrin_istatistik()
returns json language sql stable security definer set search_path = public as $$
  select json_build_object(
    'bugun', (select count(distinct ziyaretci) from public.olaylar
              where tur = 'ziyaret'
                and zaman >= (date_trunc('day', now() at time zone 'Europe/Istanbul') at time zone 'Europe/Istanbul')),
    'bu_ay', (select count(distinct ziyaretci) from public.olaylar
              where tur = 'ziyaret'
                and zaman >= (date_trunc('month', now() at time zone 'Europe/Istanbul') at time zone 'Europe/Istanbul')),
    'toplam', (select count(distinct ziyaretci) from public.olaylar where tur = 'ziyaret'),
    'en_cok', coalesce((
      select json_agg(x) from (
        select u.id, u.ad, count(*) as sayi
        from public.olaylar o join public.urunler u on u.id = o.urun_id
        where o.tur = 'goruntuleme' and u.aktif and o.zaman > now() - interval '30 days'
        group by u.id, u.ad
        order by sayi desc
        limit 5
      ) x), '[]'::json)
  );
$$;

-- ---------- YÖNETİM FONKSİYONLARI (sadece yönetici) ----------

create or replace function public.satis_ekle(p_urun_id bigint, p_adet int, p_birim_fiyat numeric,
                                             p_musteri text default '', p_stoktan_dus boolean default true)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.yonetici_mi() then raise exception 'Yetkisiz işlem'; end if;
  insert into public.satislar (urun_id, adet, birim_fiyat, kdv, musteri)
    select p_urun_id, p_adet, p_birim_fiyat, u.kdv, coalesce(p_musteri, '')
    from public.urunler u where u.id = p_urun_id;
  if not found then raise exception 'Ürün bulunamadı'; end if;
  if p_stoktan_dus then
    update public.urunler set stok = greatest(0, stok - p_adet) where id = p_urun_id;
  end if;
end $$;

create or replace function public.satis_sil(p_id bigint, p_stok_iade boolean default true)
returns void language plpgsql security definer set search_path = public as $$
declare s public.satislar;
begin
  if not public.yonetici_mi() then raise exception 'Yetkisiz işlem'; end if;
  delete from public.satislar where id = p_id returning * into s;
  if s.id is not null and p_stok_iade and s.urun_id is not null then
    update public.urunler set stok = stok + s.adet where id = s.urun_id;
  end if;
end $$;

-- Bir zaman aralığının özeti (aylık rapor ve önceki ay kıyası için)
create or replace function public.donem_ozet(bas timestamptz, son timestamptz)
returns json language sql stable security definer set search_path = public as $$
  select json_build_object(
    'ziyaretci',    (select count(distinct ziyaretci) from public.olaylar where zaman >= bas and zaman < son),
    'goruntuleme',  (select count(*) from public.olaylar where tur = 'goruntuleme' and zaman >= bas and zaman < son),
    'al_tik',       (select count(*) from public.olaylar where tur = 'al_tik' and zaman >= bas and zaman < son),
    'satis_adet',   (select coalesce(sum(adet), 0) from public.satislar where zaman >= bas and zaman < son),
    'satis_sayisi', (select count(*) from public.satislar where zaman >= bas and zaman < son),
    'ciro',         (select coalesce(round(sum(adet * birim_fiyat * (1 + kdv / 100.0)), 2), 0)
                     from public.satislar where zaman >= bas and zaman < son)
  );
$$;
revoke execute on function public.donem_ozet(timestamptz, timestamptz) from public, anon;

-- Aylık istatistik: günlük seri + ürün bazında tablo + özet + önceki ay
create or replace function public.ay_istatistik(p_yil int, p_ay int)
returns json language plpgsql stable security definer set search_path = public as $$
declare
  yb   timestamp   := make_timestamp(p_yil, p_ay, 1, 0, 0, 0);
  bas  timestamptz := yb at time zone 'Europe/Istanbul';
  son  timestamptz := (yb + interval '1 month') at time zone 'Europe/Istanbul';
  obas timestamptz := (yb - interval '1 month') at time zone 'Europe/Istanbul';
  sonuc json;
begin
  if not public.yonetici_mi() then raise exception 'Yetkisiz işlem'; end if;

  with o as (
    select (zaman at time zone 'Europe/Istanbul')::date as gun, tur, ziyaretci, urun_id
    from public.olaylar where zaman >= bas and zaman < son
  ), s as (
    select (zaman at time zone 'Europe/Istanbul')::date as gun, urun_id, adet,
           adet * birim_fiyat * (1 + kdv / 100.0) as ciro
    from public.satislar where zaman >= bas and zaman < son
  ), gunler as (
    select d::date as gun
    from generate_series(yb, yb + interval '1 month' - interval '1 day', interval '1 day') d
  ), og as (
    select gun, count(distinct ziyaretci) as ziyaretci,
           count(*) filter (where tur = 'goruntuleme') as goruntuleme,
           count(*) filter (where tur = 'al_tik') as al_tik
    from o group by gun
  ), sg as (
    select gun, sum(adet) as satis_adet, sum(ciro) as ciro from s group by gun
  ), ou as (
    select urun_id, count(*) filter (where tur = 'goruntuleme') as goruntuleme,
           count(*) filter (where tur = 'al_tik') as al_tik
    from o where urun_id is not null group by urun_id
  ), su as (
    select urun_id, sum(adet) as satis_adet, sum(ciro) as ciro from s group by urun_id
  )
  select json_build_object(
    'gunluk', (
      select json_agg(json_build_object(
        'gun', extract(day from g.gun)::int,
        'ziyaretci', coalesce(og.ziyaretci, 0),
        'goruntuleme', coalesce(og.goruntuleme, 0),
        'al_tik', coalesce(og.al_tik, 0),
        'satis_adet', coalesce(sg.satis_adet, 0),
        'ciro', coalesce(round(sg.ciro, 2), 0)
      ) order by g.gun)
      from gunler g left join og using (gun) left join sg using (gun)
    ),
    'urunler', coalesce((
      select json_agg(json_build_object(
        'urun_id', u.id, 'ad', u.ad, 'kod', u.kod, 'kategori', u.kategori,
        'goruntuleme', coalesce(ou.goruntuleme, 0),
        'al_tik', coalesce(ou.al_tik, 0),
        'satis_adet', coalesce(su.satis_adet, 0),
        'ciro', coalesce(round(su.ciro, 2), 0)
      ))
      from public.urunler u
      left join ou on ou.urun_id = u.id
      left join su on su.urun_id = u.id
      where ou.urun_id is not null or su.urun_id is not null
    ), '[]'::json),
    'ozet', public.donem_ozet(bas, son),
    'onceki', public.donem_ozet(obas, bas)
  ) into sonuc;

  return sonuc;
end $$;

